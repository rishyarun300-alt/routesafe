-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.hazard_reports (
  id bigint generated by default as identity primary key,
  road_name text not null check (char_length(road_name) between 1 and 120),
  hazard_type text not null,
  risk_level text not null default 'medium' check (risk_level in ('high','medium','low')),
  description text not null check (char_length(description) between 1 and 500),
  latitude double precision null check (latitude is null or latitude between -90 and 90),
  longitude double precision null check (longitude is null or longitude between -180 and 180),
  created_at timestamptz not null default now()
);
alter table public.hazard_reports enable row level security;
-- Public read + public insert are suitable only for a student/demo prototype.
-- Before public launch, add Supabase Auth, abuse protection and moderation.
drop policy if exists "Anyone can read hazard reports" on public.hazard_reports;
create policy "Anyone can read hazard reports" on public.hazard_reports for select to anon, authenticated using (true);
drop policy if exists "Anyone can submit hazard reports" on public.hazard_reports;
create policy "Anyone can submit hazard reports" on public.hazard_reports for insert to anon, authenticated with check (
  char_length(road_name) between 1 and 120 and char_length(description) between 1 and 500 and risk_level in ('high','medium','low')
);
-- Enable Realtime for the table. If this statement says it is already a member, that is okay.
alter publication supabase_realtime add table public.hazard_reports;
